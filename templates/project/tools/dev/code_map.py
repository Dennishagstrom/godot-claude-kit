#!/usr/bin/env python3
"""Writes docs/code_map.md: every game script with its class name, size and the
first sentence of its ## doc comment, grouped by folder. Agents read (or grep)
the map instead of searching the whole tree, which saves a lot of tokens.

    python3 -I tools/dev/code_map.py          # rewrite docs/code_map.md
    python3 -I tools/dev/code_map.py --check  # exit 1 if a script is missing from the map

Give every script a one-line `## doc comment` right under extends/class_name:
that line is what shows up here.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "docs", "code_map.md")
# Folders that are not game code (tests, third-party addons, worktrees, import cache).
EXCLUDE = ("tests/", "addons/", ".claude/", ".godot/", "build/")
# Scripts above this many lines are flagged: split them before adding more.
LARGE = 800
SUMMARY_MAX = 110


def list_scripts():
    try:
        out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard", "*.gd"],
                             cwd=ROOT, capture_output=True, text=True, check=True).stdout.split("\n")
        files = [f for f in out if f.endswith(".gd")]
    except (OSError, subprocess.CalledProcessError):
        files = []
        for base, dirs, names in os.walk(ROOT):
            dirs[:] = [d for d in dirs if not d.startswith(".")]
            for n in names:
                if n.endswith(".gd"):
                    files.append(os.path.relpath(os.path.join(base, n), ROOT).replace(os.sep, "/"))
    return sorted(f for f in set(files) if not f.startswith(EXCLUDE) and os.path.exists(os.path.join(ROOT, f)))


def summary(lines):
    """First sentence of the leading ## doc comment."""
    text = []
    for line in lines[:40]:
        s = line.strip()
        if s.startswith("##"):
            text.append(s.lstrip("#").strip())
            if "." in text[-1] or len(" ".join(text)) > SUMMARY_MAX:
                break
        elif text:
            break
    out = re.split(r"(?<=\.)\s", " ".join(text), maxsplit=1)[0]
    if len(out) > SUMMARY_MAX:
        out = out[: SUMMARY_MAX - 1].rstrip() + "…"
    return out.replace("|", "/")


def build():
    groups = {}
    for f in list_scripts():
        with open(os.path.join(ROOT, f), encoding="utf-8", errors="replace") as fh:
            lines = fh.read().splitlines()
        cls = next((l.split()[1] for l in lines[:10] if l.startswith("class_name ")), "")
        groups.setdefault(os.path.dirname(f) or ".", []).append((os.path.basename(f), cls, len(lines), summary(lines)))
    out = ["# Code map", "",
           "Generated by `tools/dev/code_map.py` (run it after adding, moving or splitting scripts).",
           f"Every game script: class, lines, what it is. ⚠ = over {LARGE} lines: extract a part before adding more.",
           "Autoloads: project.godot `[autoload]`. Tests: tests/integration/suites.txt.", ""]
    if not groups:
        out.append("(no scripts yet)")
    for folder in sorted(groups):
        out += [f"## {folder}/", ""]
        for name, cls, n, desc in groups[folder]:
            flag = " ⚠" if n > LARGE else ""
            cls_txt = f" `{cls}`" if cls else ""
            out.append(f"- **{name}**{cls_txt} ({n}{flag}) {desc}".rstrip())
        out.append("")
    return "\n".join(out) + "\n"


def listing(text):
    folder, out = "", set()
    for line in text.splitlines():
        if line.startswith("## "):
            folder = line[3:]
        m = re.match(r"- \*\*([^*]+)\*\*", line)
        if m:
            out.add(folder + m.group(1))
    return out


def main():
    text = build()
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        # Sizes and summaries drift all the time; only the file list matters.
        if listing(old) != listing(text):
            print("docs/code_map.md is stale: run python3 -I tools/dev/code_map.py")
            sys.exit(1)
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
